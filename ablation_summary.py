"""
ablation_summary.py

Tables and a figure for the intervention ablations requested in review:
  (A) benign-agent intervention: the k* message is generated by the
      non-adversarial version of the k* agent (run_experiments_v3.py --cf-mode benign)
      instead of the fixed neutral text.
  (B) no-adversary episodes: every agent benign (run_experiments_v3.py --no-adversary).

Inputs are evaluate_result.py outputs: --csv-dir from a run with --benign-root,
and --noadv-csv-dir from a run on the no-adversary root.

Outputs (in --output-dir):
  intervention_ablation.csv  ASE under neutral vs benign intervention (+ replay),
                             with outcome-transition counts and per-row agreement
  kstar_messages.csv         length of the factual, neutral and benign k* messages,
                             and how often each contains the row's target keyword(s)
  noadv_asr.csv              ASR with the adversary vs. with all agents benign
  fig4_intervention_ablation.{pdf,png}  (in --fig-dir)

Usage:
    python ablation_summary.py --csv-dir outputs/outputs_qwen/ --noadv-csv-dir outputs/outputs_qwen_noadv/ \
        --baseline-root results/results_v2_qwen_baseline --benign-root results/results_v3_qwen_benign \
        --fig-dir figures/figures_qwen/

    For Llama add --model-id meta-llama/Meta-Llama-3.1-8B-Instruct and the llama dirs.

    Compact one-row figure with both models (used in the paper's main text):
    python ablation_summary.py --combined outputs/outputs_qwen/ outputs/outputs_llama/ --fig-dir figures/
"""

import argparse
import json
import os
import warnings
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

import paper_style as ps
ps.apply()

ADV_AGENTS = {
    "travel_planning": "PLANNER_AGENT",
    "financial_article_writing": "CHIEF_EDITOR",
    "code_generation": "CEO",
    "multi_agent_debate": "agent_4",
}
ENV_ORDER = ["travel_planning", "code_generation", "multi_agent_debate", "financial_article_writing"]
ENV_LABELS = {
    "travel_planning": "Travel Planning",
    "code_generation": "Code Generation",
    "multi_agent_debate": "Multi-Agent Debate",
    "financial_article_writing": "Financial Article Writing",
}
MODE_COLORS = {"baseline": ps.GOLD, "benign": ps.BLUE}   # neutral text (intervened call) / benign agent
MODE_LABELS = {"baseline": "Neutral text", "benign": "Benign agent"}


def read_per_row(path):
    df = pd.read_csv(path)
    df["safe"] = df["safe"].astype(str).str.lower().isin(["true", "1"])
    df["row_id"] = df["row_id"].astype(int)
    return df


def transition(yf, ce):
    if yf == 1 and ce <= -0.5:
        return "prevented"
    if yf == 0 and ce >= 0.5:
        return "induced"
    return "unchanged"


def intervention_table(per_row):
    rows = []
    for env in ENV_ORDER:
        for safe in [False, True]:
            sub = per_row[(per_row["environment"] == env) & (per_row["safe"] == safe)]
            if sub.empty:
                continue
            piv = sub.pivot_table(index="row_id", columns="cf_mode", values="causal_effect_mean")
            yf = sub.drop_duplicates("row_id").set_index("row_id")["y_factual"]
            out = {"environment": env, "safe": safe}
            for mode in ["baseline", "benign", "replay"]:
                if mode not in piv:
                    continue
                ce = piv[mode].dropna()
                out[f"ase_{mode}"] = ce.mean()
                out[f"n_{mode}"] = len(ce)
                if mode != "replay":
                    tr = [transition(yf[r], c) for r, c in ce.items()]
                    out[f"prevented_{mode}"] = tr.count("prevented")
                    out[f"induced_{mode}"] = tr.count("induced")
            if {"baseline", "benign"} <= set(piv.columns):
                both = piv[["baseline", "benign"]].dropna()
                out["n_paired"] = len(both)
                out["same_outcome_frac"] = float((both["baseline"] == both["benign"]).mean())
                out["ase_diff_benign_minus_neutral"] = float((both["benign"] - both["baseline"]).mean())
            rows.append(out)
    return pd.DataFrame(rows)


def _keywords(kw):
    if not isinstance(kw, str) or kw.strip() in ("", "None", "nan"):
        return []
    return [k.strip().lower() for k in kw.split("/") if k.strip()]


def kstar_table(baseline_root, benign_root, model_name):
    rows = []
    for env in ENV_ORDER:
        for safe in [False, True]:
            rel = Path(f"env={env}") / f"model={model_name}" / f"adv={ADV_AGENTS[env]}"
            if safe:
                rel = rel / "safe=True"
            recs = []
            for idx in sorted((Path(benign_root) / rel).glob("row=*/index.json")):
                base_idx = Path(baseline_root) / rel / idx.parent.name / "index.json"
                if not base_idx.exists():
                    continue
                bi = json.load(open(idx))["counterfactual_runs"][0]["intervention"]
                ni = json.load(open(base_idx))["counterfactual_runs"][0]["intervention"]
                kws = _keywords(json.load(open(idx.parent / "factual.json")).get("keywords"))
                has = (lambda t: any(k in (t or "").lower() for k in kws)) if kws else (lambda t: np.nan)
                recs.append({
                    "len_factual": len(bi.get("factual_response_text") or ""),
                    "len_neutral": len(ni.get("cf_text") or ""),
                    "len_benign": len(bi.get("cf_text") or ""),
                    "kw_factual": has(bi.get("factual_response_text")),
                    "kw_benign": has(bi.get("cf_text")),
                    "same_kstar": bi.get("resolved_cf_call_idx") == ni.get("resolved_cf_call_idx"),
                })
            if not recs:
                continue
            d = pd.DataFrame(recs)
            rows.append({
                "environment": env, "safe": safe, "n": len(d),
                "same_kstar_frac": d["same_kstar"].mean(),
                "len_factual_mean": d["len_factual"].mean(),
                "len_factual_median": d["len_factual"].median(),
                "len_neutral_mean": d["len_neutral"].mean(),
                "len_benign_mean": d["len_benign"].mean(),
                "len_benign_median": d["len_benign"].median(),
                "n_rows_with_keywords": int(d["kw_factual"].notna().sum()),
                "kw_in_factual_frac": d["kw_factual"].dropna().astype(float).mean(),
                "kw_in_benign_frac": d["kw_benign"].dropna().astype(float).mean(),
            })
    return pd.DataFrame(rows)


def noadv_table(csv_dir, noadv_csv_dir):
    adv = pd.read_csv(os.path.join(csv_dir, "asr.csv"))
    clean = pd.read_csv(os.path.join(noadv_csv_dir, "asr.csv"))
    m = adv.merge(clean, on=["environment", "safe"], suffixes=("_adversary", "_no_adversary"))
    m["asr_lift"] = m["asr_adversary"] - m["asr_no_adversary"]
    m["env_order"] = m["environment"].map({e: i for i, e in enumerate(ENV_ORDER)})
    return m.sort_values(["env_order", "safe"]).drop(columns="env_order")


def fig_ablation(tab, fig_dir, model_label):
    """ASE per environment under the neutral-text vs benign-agent intervention,
    one panel per safety condition. Bars are means of per-row effects in {-1,0,1}."""
    os.makedirs(fig_dir, exist_ok=True)
    envs = [e for e in ENV_ORDER if e in tab["environment"].values]
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.6), sharey=True)
    width = 0.36
    x = np.arange(len(envs))
    for ax, safe in zip(axes, [False, True]):
        sub = tab[tab["safe"] == safe].set_index("environment").reindex(envs)
        for j, mode in enumerate(["baseline", "benign"]):
            vals = sub[f"ase_{mode}"].values
            ax.bar(x + (j - 0.5) * width, vals, width=width - 0.03,
                   color=MODE_COLORS[mode], label=MODE_LABELS[mode], zorder=2)
        ax.axhline(0, color="#333", linewidth=0.7, zorder=3)
        ax.set_xticks(x)
        ax.set_xticklabels([ENV_LABELS[e].replace(" ", "\n", 1) for e in envs], fontsize=8)
        ax.set_title("Safe" if safe else "Non-safe", loc="left")
        ax.grid(axis="y", color="#e5e5e5", linewidth=0.6, zorder=0)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.tick_params(axis="x", length=0)
    axes[0].set_ylabel("ASE at $k^\\ast$")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.tight_layout(rect=[0, 0, 1, 0.9])
    fig.legend(handles, labels, loc="upper left", bbox_to_anchor=(0.08, 1.0), ncol=2, frameon=False)
    if model_label:
        fig.text(0.99, 0.975, model_label, ha="right", va="top", fontsize=9, color="#555")
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(fig_dir, f"fig4_intervention_ablation.{ext}"), bbox_inches="tight")
    plt.close(fig)
    print(f"Saved figure → {os.path.join(fig_dir, 'fig4_intervention_ablation.pdf')}")



ENV_SHORT = {"travel_planning": "TP", "code_generation": "CG",
             "multi_agent_debate": "MAD", "financial_article_writing": "FAW"}


def fig_ablation_combined(csv_dirs, model_labels, out_path):
    """Compact one-row version for the paper, drawn at the full text width: one
    panel per (model, safety condition), environments as short labels."""
    tabs = [pd.read_csv(os.path.join(d, "intervention_ablation.csv")) for d in csv_dirs]
    for t in tabs:
        t["safe"] = t["safe"].astype(str).str.lower().isin(["true", "1"])
    lim = max(max(t["ase_baseline"].abs().max(), t["ase_benign"].abs().max()) for t in tabs) * 1.12
    fig, axes = plt.subplots(1, 2 * len(tabs), figsize=(ps.TEXTWIDTH, 1.75), sharey=True,
                             layout="constrained")
    width = 0.38
    for k, (tab, label) in enumerate(zip(tabs, model_labels)):
        envs = [e for e in ENV_ORDER if e in tab["environment"].values]
        x = np.arange(len(envs))
        for m, safe in enumerate([False, True]):
            ax = axes[2 * k + m]
            sub = tab[tab["safe"] == safe].set_index("environment").reindex(envs)
            for j, mode in enumerate(["baseline", "benign"]):
                ax.bar(x + (j - 0.5) * width, sub[f"ase_{mode}"].values, width=width - 0.04,
                       color=MODE_COLORS[mode], label=MODE_LABELS[mode], zorder=2)
            ax.axhline(0, color=ps.INK, linewidth=0.6, zorder=3)
            ax.set_xticks(x, [ENV_SHORT[e] for e in envs])
            ax.set_ylim(-lim, lim)
            ax.set_title(f"{label}, {'safe' if safe else 'non-safe'}", fontsize=8)
            ax.grid(axis="y", color=ps.GRID, linewidth=0.5, zorder=0)
            ax.tick_params(axis="x", length=0)
    axes[0].set_ylabel(r"ACE at $k^\ast$")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside upper center", ncol=2)
    return ps.save(fig, os.path.splitext(out_path)[0])


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv-dir", default=None, help="evaluate_result.py output run with --benign-root")
    ap.add_argument("--noadv-csv-dir", default=None, help="evaluate_result.py output on the no-adversary root")
    ap.add_argument("--baseline-root", default="results/results_v2_qwen_baseline")
    ap.add_argument("--benign-root", default="results/results_v3_qwen_benign")
    ap.add_argument("--model-id", default="Qwen/Qwen3-8B")
    ap.add_argument("--output-dir", default=None, help="defaults to --csv-dir")
    ap.add_argument("--fig-dir", default="figures/")
    ap.add_argument("--combined", nargs="+", default=None, metavar="CSV_DIR",
                    help="only draw the compact one-row figure from these csv dirs "
                         "(e.g. outputs/outputs_qwen/ outputs/outputs_llama/) into --fig-dir and exit")
    ap.add_argument("--combined-labels", nargs="+", default=["Qwen3-8B", "Llama-3.1-8B"])
    args = ap.parse_args()
    if args.combined:
        fig_ablation_combined(args.combined, args.combined_labels,
                              os.path.join(args.fig_dir, "fig4_intervention_ablation_combined.pdf"))
        raise SystemExit(0)
    if args.csv_dir is None:
        ap.error("--csv-dir is required (unless --combined is given)")
    out_dir = args.output_dir or args.csv_dir
    os.makedirs(out_dir, exist_ok=True)
    model_name = args.model_id.split("/")[-1]
    pd.set_option("display.width", 200)

    per_row = read_per_row(os.path.join(args.csv_dir, "per_row.csv"))
    tab = intervention_table(per_row)
    tab.to_csv(os.path.join(out_dir, "intervention_ablation.csv"), index=False)
    print("\n── Intervention ablation (ASE at k*) ──")
    print(tab.round(3).to_string(index=False))

    ks = kstar_table(args.baseline_root, args.benign_root, model_name)
    ks.to_csv(os.path.join(out_dir, "kstar_messages.csv"), index=False)
    print("\n── k* message length (chars) and target-keyword presence ──")
    print(ks.round(3).to_string(index=False))

    if args.noadv_csv_dir:
        na = noadv_table(args.csv_dir, args.noadv_csv_dir)
        na.to_csv(os.path.join(out_dir, "noadv_asr.csv"), index=False)
        print("\n── ASR with adversary vs. all agents benign ──")
        print(na.round(3).to_string(index=False))

    fig_ablation(tab, args.fig_dir, model_name)
    print(f"\nTables written to {out_dir}")
